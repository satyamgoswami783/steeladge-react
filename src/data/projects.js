export const projectAliases = Object.fromEntries(Object.entries(projectGroups).flatMap(([slug, aliases]) => aliases.map((alias) => [alias, slug])));
export const projectsData = projectEntries
    .filter((project) => !Object.hasOwn(projectAliases, project.slug))
    .map((project) => {
    const members = projectEntries.filter((entry) => projectGroups[project.slug]?.includes(entry.slug));
    return {
        ...project,
        gallery: [...new Set([
                project.image,
                ...project.gallery,
                ...members.flatMap((entry) => [entry.image, ...entry.gallery]),
            ])],
    };
});
export function getProjectBySlug(slug) {
    const canonicalSlug = Object.hasOwn(projectAliases, slug) ? projectAliases[slug] : slug;
    return projectsData.find((project) => project.slug === canonicalSlug);
}
export function getProjectsForService(serviceSlug) {
    const matchingSlugs = new Set(projectEntries
        .filter((project) => project.relatedServiceSlug === serviceSlug)
        .map((project) => projectAliases[project.slug] ?? project.slug));
    return projectsData.filter((project) => matchingSlugs.has(project.slug));
}
